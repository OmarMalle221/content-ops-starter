import { z } from 'zod';
import { countrySchema, emailSchema, localeSchema, passwordSchema } from './common';
import { mfaCodeSchema, webAuthnAssertionSchema } from './passkeys';

export const registerSchema = z.object({
  email: emailSchema,
  password: passwordSchema,
  firstName: z.string().trim().min(1).max(80),
  lastName: z.string().trim().min(1).max(80),
  country: countrySchema,
  locale: localeSchema.default('fr'),
  phone: z.string().trim().max(30).optional(),
  acceptTerms: z.literal(true, { errorMap: () => ({ message: 'Terms must be accepted' }) }),
  /** Optional transaction invitation token so a seller can register straight from an invite link. */
  invitationToken: z.string().min(16).max(256).optional(),
});
export type RegisterInput = z.infer<typeof registerSchema>;

export const loginSchema = z.object({
  email: emailSchema,
  password: z.string().min(1).max(128),
});
export type LoginInput = z.infer<typeof loginSchema>;

/**
 * Login MFA step (POST /v1/auth/mfa/verify): a TOTP code, a single-use recovery code, or a passkey
 * assertion answering a STEP_UP challenge issued to this (pre-MFA) session.
 */
export const mfaVerifySchema = z
  .object({ code: mfaCodeSchema.optional(), passkeyAssertion: webAuthnAssertionSchema.optional() })
  .refine((v) => Boolean(v.code || v.passkeyAssertion), {
    message: 'A code or a passkey assertion is required',
    path: ['code'],
  });
export type MfaVerifyInput = z.infer<typeof mfaVerifySchema>;

/** Enrolment confirmation: only a TOTP code generated by the freshly configured application. */
export const mfaEnableSchema = z.object({ code: z.string().regex(/^\d{6}$/) });
export type MfaEnableInput = z.infer<typeof mfaEnableSchema>;

/** POST /v1/auth/mfa/disable — fresh proof: TOTP code, recovery code or passkey assertion. */
export const mfaDisableSchema = mfaVerifySchema;
export type MfaDisableInput = z.infer<typeof mfaDisableSchema>;

export const changePasswordSchema = z.object({
  currentPassword: z.string().min(1).max(128),
  newPassword: passwordSchema,
});

export const updateProfileSchema = z.object({
  firstName: z.string().trim().min(1).max(80).optional(),
  lastName: z.string().trim().min(1).max(80).optional(),
  phone: z.string().trim().max(30).nullable().optional(),
  locale: localeSchema.optional(),
});
export type UpdateProfileInput = z.infer<typeof updateProfileSchema>;
